import "dotenv/config";

function required(name: string, fallback?: string): string {
  const v = process.env[name] ?? fallback;
  if (v === undefined) throw new Error(`Missing required env var ${name}`);
  return v;
}

export const config = {
  port: Number(process.env.PORT ?? 4000),
  databaseUrl: required("DATABASE_URL"),
  jwtSecret: required("JWT_SECRET", "dev-insecure-secret-change-me"),
  cookieSecret: required("COOKIE_SECRET", "dev-insecure-cookie-secret"),
  publicUrl: process.env.PUBLIC_URL ?? "http://localhost:4000",
  // relative to server/src (dev) or server/dist (build) — both are one level under server/
  webDistPath: process.env.WEB_DIST_PATH ?? "../../web/dist",
  // Default-off: open self-registration must be explicitly turned on by an
  // admin (at runtime, via InstanceSetting) or via this env var as the
  // instance's initial default. Either way it never applies to the very
  // first (bootstrap) account — that one is gated by setupToken instead.
  allowRegistrationDefault: (process.env.ALLOW_REGISTRATION ?? "false") === "true",
  // One-time token generated by setup.sh, required to create the very
  // first (admin) account. Left unset, bootstrap is unguarded (useful for
  // local development without running setup.sh).
  setupToken: process.env.SETUP_TOKEN,
};
